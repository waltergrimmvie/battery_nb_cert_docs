import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const files = [
  "startup/startup.js",
  "startup/desk.js",
  "setup/login_user.js",
  "setup/create_indexed.js",
  "database/indexed/files.js",
  "main_page/construct_main_page.js",
  "main_page/read_docx.js",
  "menu_bar/construct_design/construct_design.js",
  "menu_bar/online_users.js",
  "menu_bar/populate/populate.js",
];

const browserFiles = {};
for (const file of files) {
  browserFiles[`/${file}`] = readFileSync(join(root, file), "utf8");
}

const out = `// Generated by scripts/embed-browser.mjs. Do not edit by hand.
// Run: node scripts/embed-browser.mjs
export const browserFiles = ${JSON.stringify(browserFiles, null, 2)};
`;

writeFileSync(join(root, "src/browser-files.js"), out);
console.log(`wrote ${files.length} modules into src/browser-files.js`);
